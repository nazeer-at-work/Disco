#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourceDir = path.join(root, 'android', 'app', 'src', 'main', 'res', 'drawable-nodpi');
const NON_ICON_DRAWABLES = new Set([
  'ic_disco_back',
  'ic_disco_mask',
  'ic_disco_upon',
  'ic_disco_back_1',
  'iconback',
  'iconmask',
  'iconupon',
]);
const generatedIconsPath = path.join(root, 'src', 'config', 'system-icons.generated.json');
const generatedImageMapPath = path.join(root, 'src', 'config', 'icon-image-map.generated.ts');

function toLabel(id) {
  const parts = id
    .replace(/[_-]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((part) => {
      const lower = part.toLowerCase();
      if (lower === 'yt') return 'YT';
      if (lower.length <= 2) return lower.toUpperCase();
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    });
  return parts.join(' ');
}

function stableHue(input) {
  let hash = 0;
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash * 31 + input.charCodeAt(i)) % 4294967291;
  }
  const hue = hash % 360;
  const saturation = 58 + (hash % 9);
  const lightness = 62 + (hash % 8);
  return hslToHex(hue, saturation, lightness);
}

function hslToHex(h, s, l) {
  const sat = s / 100;
  const light = l / 100;
  const c = (1 - Math.abs(2 * light - 1)) * sat;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = light - c / 2;

  let r = 0;
  let g = 0;
  let b = 0;

  if (h < 60) {
    r = c;
    g = x;
  } else if (h < 120) {
    r = x;
    g = c;
  } else if (h < 180) {
    g = c;
    b = x;
  } else if (h < 240) {
    g = x;
    b = c;
  } else if (h < 300) {
    r = x;
    b = c;
  } else {
    r = c;
    b = x;
  }

  const toHex = (value) => {
    const channel = Math.round((value + m) * 255)
      .toString(16)
      .padStart(2, '0');
    return channel;
  };

  return `#${toHex(r)}${toHex(g)}${toHex(b)}`.toUpperCase();
}

function main() {
  if (!fs.existsSync(sourceDir)) {
    throw new Error(`Icon source directory does not exist: ${sourceDir}`);
  }

  const drawables = fs
    .readdirSync(sourceDir)
    .filter((file) => file.endsWith('.webp'))
    .map((file) => path.basename(file, '.webp'))
    .filter((drawable) => !NON_ICON_DRAWABLES.has(drawable) && !drawable.startsWith('ic_disco_symbol_'))
    .sort();

  const generatedIcons = drawables.map((drawable) => {
    const id = drawable;
    const label = toLabel(id);
    const hue = stableHue(id);
    return {
      id,
      name: label,
      label,
      hue,
      category: 'Icons',
      preview: {
        color: hue,
        symbol: id,
        source: { uri: drawable },
      },
      tags: [id.replace(/[_-]+/g, ' ')],
      requiresCoin: false,
      drawable,
    };
  });

  const generatedJson = `${JSON.stringify(generatedIcons, null, 2)}\n`;
  fs.writeFileSync(generatedIconsPath, generatedJson, 'utf8');

  const imageMapEntries = drawables
    .map((drawable) => `  '${drawable}': { uri: '${drawable}' },`)
    .join('\n');

  const generatedTs = `import { ImageSourcePropType } from 'react-native';

// Auto-generated by scripts/generate-gallery-manifest.js — do not edit by hand.
export const iconImageMap: Record<string, ImageSourcePropType> = {
${imageMapEntries}
};
`;

  fs.writeFileSync(generatedImageMapPath, generatedTs, 'utf8');

  console.log(`[gallery-manifest] Wrote ${generatedIcons.length} icons and ${drawables.length} drawable URI mappings.`);
}

main();
